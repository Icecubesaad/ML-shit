def f(x, n=3):
    return f"{float(x):.{n}f}"


def add_heading(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    return h


def add_para(doc, text, bold=False, italic=False, size=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    if size:
        r.font.size = Pt(size)
    return p


def add_table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = str(h)
        for p in hdr[i].paragraphs:
            for r in p.runs:
                r.bold = True
                r.font.size = Pt(8)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
            for p in cells[i].paragraphs:
                for r in p.runs:
                    r.font.size = Pt(8)
    return t


def add_fig(doc, path, caption, width=5.8):
    if not path.exists():
        add_para(doc, f"[MISSING FIGURE: {path.name}]", italic=True)
        return
    p = doc.add_paragraph()
    p.alignment = 1
    p.add_run().add_picture(str(path), width=Inches(width))
    c = doc.add_paragraph()
    c.alignment = 1
    r = c.add_run(caption)
    r.italic = True
    r.font.size = Pt(8)
    r.font.color.rgb = RGBColor(0x44, 0x44, 0x44)


def row_for(stats, subset, comp):
    r = stats[(stats["subset"] == subset) & (stats["comparison"] == comp)]
    if r.empty:
        return None
    return r.iloc[0]


def mean_of(stats, subset, arm):
    vals = []
    s = stats[stats["subset"] == subset]
    for _, r in s.iterrows():
        if r["arm_a"] == arm:
            vals.append(float(r["arm_a_mean"]))
        if r["arm_b"] == arm:
            vals.append(float(r["arm_b_mean"]))
    return sum(vals) / len(vals) if vals else float("nan")


