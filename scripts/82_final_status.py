"""Regenerate the final-status block at the top of reports/final_research_report.md from artifacts.

The block sits between the FINAL-STATUS markers; everything outside it is untouched. The same file is
copied to artifacts/reports/ so the deliverable gate V3 can compare the two. No number is typed here.
"""

from __future__ import annotations

import importlib.util
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- FINAL-STATUS:BEGIN -->", "<!-- FINAL-STATUS:END -->"


def _paper():
    spec = importlib.util.spec_from_file_location("build_paper", ROOT / "scripts" / "80_build_paper.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["build_paper"] = mod
    spec.loader.exec_module(mod)
    return mod


def block() -> str:
    bp = _paper()
    F = bp.load_facts()
    f, sgn = bp.f, bp.sgn
    head, dh = F["head"], F["dh"]
    res, floor = dh["results"], dh["results"]["hairy_input_floor"]
    paper = dh["provenance"]["paper"]
    q, qrows, qcmp = bp.quality_table(F)
    L = ["## Final status (generated by `scripts/82_final_status.py`; do not edit by hand)", "",
         "Research prototype only. Not clinically validated and not intended for diagnosis or patient care.", "",
         "### 1. Diffusion root cause and reproduction", "",
         f"- Root cause of the first diffusion run's failure: inverted noise-level encoding in the trainer (decision D25); "
         "the repaired trainer is covered by contract tests.",
         f"- DERMAHAIR ({dh['provenance'].get('n_pairs', '?')} public pairs; Hugging Face and Kaggle copies are byte-identical): "
         f"do-nothing floor {f(floor['psnr_up'], 2)} dB / SSIM {f(floor['ssim_up'], 4)} / LPIPS {f(floor['lpips'], 4)}; paper "
         f"{paper['psnr']:.2f} dB / {paper['ssim']:.4f}."]
    for k, nm in (("respaced_10_bf16", "released, 10 strided steps"), ("full_2000_bf16", "released, 2,000 steps")):
        if k in res:
            r = res[k]
            L.append(f"- {nm}: PSNR {f(r['psnr_up'], 2)} dB, SSIM {f(r['ssim_up'], 4)}, LPIPS {f(r['lpips'], 4)}; verdict **{r['verdict']}**.")
    L += ["", "### 2. Regenerate, retrain, re-evaluate", "",
          "| Arm | Seeds | Test macro-F1 (mean ± SD) | Balanced accuracy | Macro-AUC |", "|---|---:|---:|---:|---:|"]
    arm_order = ["A", "Astar", "B", "Cv2", "Creleased", "C"]
    if "Astarfov" in set(head.index):
        arm_order.append("Astarfov")
    for a in arm_order:
        h = head.loc[a]
        L.append(f"| {bp.LABEL[a]} | {int(h['seeds'])} | {h['macro_f1_mean']:.3f} ± {h['macro_f1_sd']:.3f} | "
                 f"{h['balanced_accuracy_mean']:.3f} | {h['auc_macro_mean']:.3f} |")
    L += ["", "| Comparison (full test) | Macro-F1 difference (95% CI) | Holm p | Established |", "|---|---|---:|---|"]
    comps = ["A-B", "A-Astar", "A-Cv2", "B-Cv2", "Cv2-Astar"]
    if bp.stat_row(F, "macro_f1", "Astarfov-A") is not None:
        comps += ["Astarfov-Astar", "Astarfov-A"]
    for comp in comps:
        r = bp.stat_row(F, "macro_f1", comp)
        L.append(f"| {comp.replace('Astar', 'A*')} ({r['family']}) | {sgn(r['difference'])} ({sgn(r['ci_low'])} to {sgn(r['ci_high'])}) | "
                 f"{bp.p_fmt(r['p_holm'])} | {'yes' if r['established'] else 'no'} |")
    L += ["", f"Image quality on {len(q)} held-out synthetic pairs: " + "; ".join(f"{r[0]} {r[1]} dB / {r[2]}" for r in qrows) + ".", "",
          "### 3. Explainability (corrected geometry)", "",
          "| Arm | Mask area | Recall ceiling | Rollout recall | Gaussian recall | Grad-CAM ln_1 recall |", "|---|---:|---:|---:|---:|---:|"]
    gm = F["xai_geo"]
    for a in ("A", "B", "Astar", "Cv2", "Creleased", "C"):
        r = bp.xai_val(F, a, bp.ROLL, "recall")
        g = bp.xai_val(F, a, bp.GC1, "recall")
        L.append(f"| {bp.SHORT[a]} | {gm.loc[a, 'mean_mask_area']:.3f} | {gm.loc[a, 'recall_ceiling']:.3f} | {r['mean']:.3f} | "
                 f"{r['baseline_gauss']:.3f} | {g['mean']:.3f} |")
    cmp = F["xai_cmp"]
    sel = cmp[(cmp.frame == "as is") & (cmp.metric == "recall") & (cmp.method.isin([bp.ROLL, bp.GC1]))]
    L += ["", f"Between-arm recall rows struck by the seed-spread rule: {int(sel['struck'].sum())} of {len(sel)}.", "",
          "### 4-5. Paper and deliverables", ""]
    man = pd.read_csv(ROOT / "reports" / "export_manifest.csv")
    L.append(f"- Checkpoints: {int((man['kind'] == 'vit').sum())} ViT and {int((man['kind'] == 'diffusion').sum())} diffusion files with SHA-256 in "
             "`reports/export_manifest.csv` (files in `exports/` and on the Modal volume under `/artifacts/exports`).")
    L.append("- Paper: `artifacts/reports/Research_Paper.docx`; results report: `artifacts/reports/Results_Report.docx`; "
             "explanation tables: `reports/xai_corrected_results.md`.")
    sp = ROOT / "reports" / "spend_log.csv"
    if sp.exists():
        d = pd.read_csv(sp)
        this = d[d["scope"].str.startswith("this session")]["est_usd"].sum()
        L.append(f"- Estimated Modal spend: this session {this:.2f} USD; all recorded work {d['est_usd'].sum():.2f} USD (upper bound; see decision D44).")
    return "\n".join(L) + "\n"


def rest_of_report() -> str:
    bp = _paper()
    F = bp.load_facts()
    head = F["head"]
    V = bp.verdicts(F)
    f = bp.f
    sp, gm = F["split"], F["xai_geo"]
    lab = {True: "supported", False: "not supported"}
    ab = bp.stat_row(F, "macro_f1", "A-B")
    cva = bp.stat_row(F, "macro_f1", "Cv2-Astar")
    cmp = F["xai_cmp"]
    sel = cmp[(cmp.frame == "as is") & (cmp.metric == "recall") & (cmp.method.isin([bp.ROLL, bp.GC1]))]
    n_struck = int(sel["struck"].sum())
    cv_ro = cmp[(cmp.a == "Cv2") & (cmp.b == "Astar") & (cmp.metric == "recall") & (cmp.method == bp.ROLL)
                & (cmp.frame == "as is")].iloc[0]
    L = ["", "## Hypothesis verdicts (computed by rule from the numbers above)", "",
         f"- **H1, image quality: {lab[V['h1']]}.** Cv2 minus DullRazor on the held-out synthetic pairs: "
         f"{bp.sgn(V['h1_psnr'][0], 2)} dB PSNR ({bp.sgn(V['h1_psnr'][1], 2)} to {bp.sgn(V['h1_psnr'][2], 2)}), "
         f"{bp.sgn(V['h1_ssim'][0], 3)} SSIM ({bp.sgn(V['h1_ssim'][1], 3)} to {bp.sgn(V['h1_ssim'][2], 3)}). Synthetic hair only.",
         f"- **H2, classification: {lab[V['h2']]}.** A minus B {bp.sgn(ab['difference'])} (Holm p {bp.p_fmt(ab['p_holm'])}); Cv2 minus the 128 px "
         f"control {bp.sgn(cva['difference'])} ({bp.sgn(cva['ci_low'])} to {bp.sgn(cva['ci_high'])}).",
         f"- **H3, explainability: {V['h3']}.** Against the resolution-matched control (Cv2 minus A*, corrected frame) the recall "
         f"difference is rollout {bp.sgn(cv_ro['difference'])} ({bp.sgn(cv_ro['ci_low'])} to {bp.sgn(cv_ro['ci_high'])}); "
         f"{n_struck} of {len(sel)} between-arm recall rows are struck by the seed-spread rule. A fixed centred Gaussian reaches "
         f"recall {f(bp.xai_val(F, 'A', bp.ROLL, 'recall')['baseline_gauss'])} (A, B) and "
         f"{f(bp.xai_val(F, 'Astar', bp.ROLL, 'recall')['baseline_gauss'])} (128 px arms) because lesions are large "
         f"(mean mask area {f(gm.loc['A', 'mean_mask_area'])} and {f(gm.loc['Astar', 'mean_mask_area'])} of the model frame) and central "
         f"({100 * gm.loc['A', 'share_masks_containing_centre']:.1f}% of masks contain the image centre).",
         ]
    if "Astarfov" in set(head.index):
        L.append(f"- **Exploratory A*-fov control:** macro-F1 {f(head.loc['Astarfov', 'macro_f1_mean'])} "
                 f"(eight seeds), against A {f(head.loc['A', 'macro_f1_mean'])} and A* "
                 f"{f(head.loc['Astar', 'macro_f1_mean'])}. It keeps A's field of view at A*'s "
                 "storage resolution; its comparisons are exploratory and reported in the paper.")
    L += [         "", "## Limitations and failure cases", "",
         "- Image-quality evidence uses synthetic hair on clean photographs; real-hair removal quality is not validated.",
         "- Our first diffusion run (arm C) failed because of a trainer defect (inverted noise-level encoding); it is kept as a recorded failure.",
         "- The released diffusion checkpoint did not reproduce the published image-quality figure on the public DERMAHAIR pairs; the matching "
         "effort stopped by the pre-stated rule and no diffusion model was trained on DERMAHAIR.",
         "- The diffusion models work at 128 px, the classifier at 224 px; seeds are eight (three for C and Creleased); the minimum detectable "
         "macro-F1 difference is about 0.04 to 0.05.",
         "- Lesion masks are single-rater (Tschandl et al., Nature Medicine 2020) and large and central, which limits localisation metrics.",
         "- The corrected explanation analysis re-scored the same test images after the geometry fix (decision D40).",
         "", "## Licence caveats (no legal conclusion)", "",
         "- HAM10000 is CC BY-NC 4.0 (non-commercial). The DM-AHR repository's README (CC BY-NC 4.0) and LICENSE file (Apache-2.0) contradict "
         "each other; commercial use of the released weights and of derived images is unresolved. See `reports/license_audit.md`.",
         "", "## Where everything is", "",
         "- Deliverables and generators: README section 'Final deliverables'. Decisions: `reports/decision_log.md` (D40 to D46 for this round). "
         "Progress ledger: `reports/PROGRESS.md`. Artifact hashes: `reports/artifact_inventory.csv`, `reports/export_manifest.csv`.",
         "- The report as it stood before this round is kept, labelled superseded, at `reports/archive/final_research_report_2026-11-13.md`.",
         f"- Split hash {sp['splits_sha256'][:16]}...; test n={sp['sizes']['test']}, lesion groups {sp['groups']['test']}.", ""]
    return "\n".join(L)


def main() -> int:
    bp = _paper()
    head = bp.load_facts()["head"]
    arms8 = ", ".join(bp.SHORT[a] for a in head.index if int(head.loc[a, "seeds"]) == 8)
    arms3 = ", ".join(bp.SHORT[a] for a in head.index if int(head.loc[a, "seeds"]) == 3)
    seed_sentence = (f"Seed counts differ by arm: {arms8} are pooled over eight seeds "
                     "(42, 123, 2026, 7, 11, 17, 23, 31); "
                     f"{arms3} are evaluated over the three pre-registered seeds (42, 123, 2026), so "
                     "three-seed numbers appear only for those two arms and are labelled as such.")
    path = ROOT / "reports" / "final_research_report.md"
    text = ("# DM-AHR-ViT: diffusion hair removal and ViT classification on HAM10000\n\n"
            "**Research prototype only. Not clinically validated and not intended for diagnosis, triage or patient care.** "
            "Generated by `scripts/82_final_status.py` from artifacts; every number is read from a file under `artifacts/`.\n\n"
            f"{seed_sentence}\n\n"
            f"{BEGIN}\n{block()}{END}\n{rest_of_report()}")
    path.write_text(text)
    dst = ROOT / "artifacts" / "reports" / "final_research_report.md"
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, dst)
    print(f"updated {path} and {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
